def make_region_list(region, subs, groups):
    if groups:
        html = ''
        for group_name, group_desc, group_subs in groups:
            # 실제 파일에 있는 subs와 교차
            valid = [s for s in group_subs if s in subs]
            if not valid:
                continue
            links = '\n          '.join(
                f'<li><a href="/{region}/{s}/">{s}</a></li>' for s in valid
            )
            html += f'''
          <h3 class="section-subtitle">{group_name} ({group_desc})</h3>
          <ul class="region-list">
          {links}
          </ul>'''
        return html
    else:
        links = '\n          '.join(
            f'<li><a href="/{region}/{s}/">{s}</a></li>' for s in subs
        )
        return f'<ul class="region-list">\n          {links}\n          </ul>'


def make_extra_sections(extra, s):
    html = ''
    for item in extra:
        title = item["h2"]
        if title.startswith(s + ' '):
            title = title[len(s)+1:]
        html += f'''
      <section class="section">
        <div class="container">
          <h2 class="section-title">{title}</h2>
          <p class="section-desc">{item["content"]}</p>
        </div>
      </section>
'''
    return html


